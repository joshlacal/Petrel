/// Returns `true` if `ch` is matched by Unicode `\p{P}` (General Category Punctuation).
#[must_use]
pub fn is_unicode_punctuation(ch: char) -> bool {
    let cp = ch as u32;
    PUNCTUATION_RANGES
        .binary_search_by(|&(start, end)| {
            if cp < start {
                std::cmp::Ordering::Greater
            } else if cp > end {
                std::cmp::Ordering::Less
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .is_ok()
}

/// Returns `true` if `ch` is matched by ECMAScript `\s` (WhiteSpace + LineTerminator + U+FEFF).
#[must_use]
pub const fn is_ecmascript_whitespace(ch: char) -> bool {
    matches!(
        ch as u32,
        0x09 | 0x0A | 0x0B | 0x0C | 0x0D | 0x20 | 0xA0 | 0x1680 | 0x2000
            ..=0x200A | 0x2028 | 0x2029 | 0x202F | 0x205F | 0x3000 | 0xFEFF
    )
}

/// Returns `true` if every character in `text` is ECMAScript whitespace.
#[must_use]
pub fn is_blank(text: &str) -> bool {
    text.chars().all(is_ecmascript_whitespace)
}

/// Returns the number of UTF-16 code units `scalars` occupy (matching JS `.length`).
#[must_use]
pub fn utf16_len(scalars: &[char]) -> usize {
    scalars.iter().map(|&c| c.len_utf16()).sum()
}

