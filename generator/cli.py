def _probe_swiftformat_version(
    cmd_prefix: Sequence[str],
    env: dict[str, str] | None = None,
) -> str | None:
    try:
        proc = subprocess.run(
            [*cmd_prefix, "--version"],
            env=env,
            capture_output=True,
            text=True,
            check=False,
            timeout=30,
        )
    except OSError:
        return None
    if proc.returncode != 0:
        return None
    return proc.stdout.strip()


def _mint_has_pinned_swiftformat(mint_exe: str, env: dict[str, str]) -> bool:
    try:
        proc = subprocess.run(
            [mint_exe, "list"],
            env=env,
            capture_output=True,
            text=True,
            check=False,
            timeout=30,
        )
    except OSError:
        return False
    if proc.returncode != 0:
        return False
    in_swiftformat = False
    for raw_line in proc.stdout.splitlines():
        stripped = raw_line.strip()
        if not stripped or stripped.startswith("🌱"):
            continue
        if stripped.startswith("-"):
            rest = stripped.lstrip("-").strip()
            version_token = rest.split()[0] if rest else ""
            if in_swiftformat and version_token == PINNED_SWIFTFORMAT_VERSION:
                return True
        else:
            in_swiftformat = stripped.lower() in (
                "swiftformat",
                "nicklockwood/swiftformat",
            )
    return False


def _make_direct_swiftformat_runner(executable: str) -> SwiftFormatRunner:
    def _run(args: Sequence[str]) -> None:
        proc = subprocess.run(
            [executable, *args],
            capture_output=True,
            text=True,
            check=False,
        )
        if proc.returncode != 0:
            detail = (proc.stderr or proc.stdout).strip()
            raise RuntimeError(
                f"SwiftFormat {PINNED_SWIFTFORMAT_VERSION} failed ({executable}): {detail}"
            )

    return _run


def _make_mint_swiftformat_runner(
    mint_exe: str,
    mint_packages_dir: Path | None = None,
) -> SwiftFormatRunner:
    def _run(args: Sequence[str]) -> None:
        with tempfile.TemporaryDirectory(prefix="petrel-mint-links-") as link_dir:
            env = dict(os.environ)
            if mint_packages_dir is not None:
                env["MINT_PATH"] = str(mint_packages_dir)
            env["MINT_LINK_PATH"] = link_dir
            proc = subprocess.run(
                [
                    mint_exe,
                    "run",
                    "--executable",
                    "swiftformat",
                    PINNED_SWIFTFORMAT_MINT_SPEC,
                    *args,
                ],
                env=env,
                capture_output=True,
                text=True,
                check=False,
            )
            if proc.returncode != 0:
                detail = (proc.stderr or proc.stdout).strip()
                raise RuntimeError(
                    f"SwiftFormat {PINNED_SWIFTFORMAT_VERSION} via Mint failed: {detail}"
                )

    return _run


def _find_pinned_swiftformat(require: bool = False) -> SwiftFormatRunner | None:
    """Resolve pinned SwiftFormat 0.61.1 strictly, never invoking an unpinned binary."""
    # 1. Explicit PETREL_SWIFTFORMAT override (must be executable and exactly 0.61.1).
    configured_sf = os.environ.get("PETREL_SWIFTFORMAT")
    if configured_sf:
        sf_path = Path(configured_sf)
        if not (sf_path.is_file() and os.access(sf_path, os.X_OK)):
            raise RuntimeError(
                f"PETREL_SWIFTFORMAT={configured_sf!r} is not an executable file "
                f"(pinned SwiftFormat {PINNED_SWIFTFORMAT_VERSION} is required)."
            )
        version = _probe_swiftformat_version([str(sf_path)])
        if version != PINNED_SWIFTFORMAT_VERSION:
            raise RuntimeError(
                f"PETREL_SWIFTFORMAT={configured_sf!r} reported version {version!r}; "
                f"pinned SwiftFormat {PINNED_SWIFTFORMAT_VERSION} is required "
                "(point PETREL_SWIFTFORMAT at SwiftFormat 0.61.1 or pass --no-format)."
            )
        return _make_direct_swiftformat_runner(str(sf_path))

    # 2. Explicit RELEASE_MINT environment variable (used by CI workflows).
    release_mint = os.environ.get("RELEASE_MINT")
    if release_mint:
        mint_path_obj = Path(release_mint)
        if not (mint_path_obj.is_file() and os.access(mint_path_obj, os.X_OK)):
            raise RuntimeError(
                f"RELEASE_MINT={release_mint!r} is not an executable Mint binary."
            )
        fallback_pkgs: Path | None = None
        if not os.environ.get("MINT_PATH"):
            candidate_pkgs = mint_path_obj.resolve().parent / "mint-packages"
            if candidate_pkgs.is_dir():
                fallback_pkgs = candidate_pkgs
        with tempfile.TemporaryDirectory(prefix="petrel-mint-probe-") as probe_links:
            probe_env = dict(os.environ)
            if fallback_pkgs is not None:
                probe_env["MINT_PATH"] = str(fallback_pkgs)
            probe_env["MINT_LINK_PATH"] = probe_links
            version = _probe_swiftformat_version(
                [
                    release_mint,
                    "run",
                    "--executable",
                    "swiftformat",
                    PINNED_SWIFTFORMAT_MINT_SPEC,
                ],
                env=probe_env,
            )
        if version != PINNED_SWIFTFORMAT_VERSION:
            raise RuntimeError(
                f"RELEASE_MINT={release_mint!r} did not provide pinned SwiftFormat "
                f"{PINNED_SWIFTFORMAT_VERSION} (got {version!r})."
            )
        return _make_mint_swiftformat_runner(release_mint, fallback_pkgs)

    # 3. Repo-local .build/release-tools/mint + mint-packages (zero network).
    for tools_root in _candidate_release_tools_roots():
        local_mint = tools_root / "mint"
        local_pkgs = tools_root / "mint-packages"
        if (
            local_mint.is_file()
            and os.access(local_mint, os.X_OK)
            and local_pkgs.is_dir()
        ):
            with tempfile.TemporaryDirectory(prefix="petrel-mint-probe-") as probe_links:
                probe_env = dict(os.environ)
                probe_env["MINT_PATH"] = str(local_pkgs)
                probe_env["MINT_LINK_PATH"] = probe_links
                if _mint_has_pinned_swiftformat(str(local_mint), probe_env):
                    version = _probe_swiftformat_version(
                        [
                            str(local_mint),
                            "run",
                            "--executable",
                            "swiftformat",
                            PINNED_SWIFTFORMAT_MINT_SPEC,
                        ],
                        env=probe_env,
                    )
                    if version == PINNED_SWIFTFORMAT_VERSION:
                        return _make_mint_swiftformat_runner(str(local_mint), local_pkgs)

    # 4. `swiftformat` on PATH only if its version is strictly 0.61.1.
    path_sf = shutil.which("swiftformat")
    if path_sf and _probe_swiftformat_version([path_sf]) == PINNED_SWIFTFORMAT_VERSION:
        return _make_direct_swiftformat_runner(path_sf)

    # 5. `mint` on PATH only if local `mint list` already has SwiftFormat 0.61.1 installed.
    path_mint = shutil.which("mint")
    if path_mint:
        with tempfile.TemporaryDirectory(prefix="petrel-mint-probe-") as probe_links:
            probe_env = dict(os.environ)
            probe_env["MINT_LINK_PATH"] = probe_links
            if _mint_has_pinned_swiftformat(path_mint, probe_env):
                version = _probe_swiftformat_version(
                    [
                        path_mint,
                        "run",
                        "--executable",
                        "swiftformat",
                        PINNED_SWIFTFORMAT_MINT_SPEC,
                    ],
                    env=probe_env,
                )
                if version == PINNED_SWIFTFORMAT_VERSION:
                    return _make_mint_swiftformat_runner(path_mint)

    if require:
        raise RuntimeError(
            f"Pinned SwiftFormat {PINNED_SWIFTFORMAT_VERSION} is required to verify Swift outputs "
            "with `--check` (committed Swift outputs are formatted with "
            f"`{PINNED_SWIFTFORMAT_MINT_SPEC}`). Set `PETREL_SWIFTFORMAT` to a "
            f"SwiftFormat {PINNED_SWIFTFORMAT_VERSION} binary, run "
            "`Scripts/bootstrap-release-tools.sh`, or pass `--no-format` to compare raw generator output."
        )
    return None


def _discover_swiftformat_config(actual_dir: Path) -> Path | None:
    """Locate a governing `.swiftformat` file without crossing package or VCS boundaries."""
    resolved = actual_dir.resolve()
    for directory in (resolved, *resolved.parents):
        cfg = directory / ".swiftformat"
        if cfg.is_file():
            return cfg
        if (
            (directory / "Package.swift").is_file()
            or (directory / ".git").exists()
            or (directory / ".jj").exists()
        ):
            return None
    return None


def _format_swift_directory(
    target_dir: Path,
    actual_dir: Path,
    manifest: dict[str, Any],
    runner: SwiftFormatRunner,
) -> None:
    if not target_dir.is_dir() or not any(target_dir.rglob("*.swift")):
        return
    cfg_path = _discover_swiftformat_config(actual_dir)
    kind = manifest.get("package", {}).get("kind", "core")
    if cfg_path is not None:
        runner(["--config", str(cfg_path), "--quiet", str(target_dir)])
        return
    if kind == "core":
        runner([*CORE_SWIFTFORMAT_ARGS, "--quiet", str(target_dir)])
        return
    with tempfile.TemporaryDirectory(prefix="petrel-swiftformat-default-") as empty_cfg_dir:
        empty_cfg = Path(empty_cfg_dir) / ".swiftformat"
        empty_cfg.write_text("", encoding="utf-8")
        runner(["--config", str(empty_cfg), "--quiet", str(target_dir)])


@contextlib.contextmanager
def _staged_manifest_outputs(
    manifest_path: Path,
    manifest: dict[str, Any],
    language: str,
    graph_path: str | None,
    default_core_roots: Sequence[str],
    *,
    no_format: bool,
    require_swiftformat: bool,
):
    """Run ``run_manifest`` into an isolated temporary directory and yield staged target tuples.

    Each yielded tuple is ``(check_label, lang_label, actual_dir, staged_dir, extension, header)``.
    """
    with tempfile.TemporaryDirectory(prefix="petrel-gen-staged-") as temp_root_str:
        temp_root = Path(temp_root_str)
        staged_manifest = json.loads(json.dumps(manifest))
        pkg_cfg = staged_manifest.get("package")
        kind = pkg_cfg.get("kind", "core") if isinstance(pkg_cfg, dict) else "core"
        swift_header = (
            APP_INTENTS_GENERATED_HEADER if kind == "app-intents" else GENERATED_SWIFT_HEADER
        )

        if kind == "app-intents":
            lex_cfg = staged_manifest.get("lexicons")
            if isinstance(lex_cfg, dict) and isinstance(lex_cfg.get("reference"), list):
                manifest_dir = manifest_path.parent.resolve()
                rewritten_refs: list[Any] = []
                for entry in lex_cfg["reference"]:
                    if isinstance(entry, str):
                        if entry in BUNDLED_LEXICONS_ALIASES or entry == CORE_REFERENCE_TOKEN:
                            rewritten_refs.append(get_bundled_core_lexicons_dir())
                        elif os.path.isabs(entry):
                            rewritten_refs.append(entry)
                        else:
                            rewritten_refs.append(str((manifest_dir / entry).resolve()))
                    else:
                        rewritten_refs.append(entry)
                lex_cfg["reference"] = rewritten_refs

        targets: list[tuple[str, str, Path, Path, str, str]] = []
        swift_format_dirs: list[tuple[Path, Path]] = []
        actual_swift = _resolve_manifest_swift_output(manifest_path, staged_manifest)
        if actual_swift is not None and language in ("swift", "both"):
            actual_lex_docs: Path | None = None
            if kind != "app-intents":
                lex_docs = staged_manifest["swift"].get("lexicon_documents")
                if (
                    isinstance(lex_docs, dict)
                    and isinstance(lex_docs.get("output"), str)
                    and lex_docs["output"]
                ):
                    actual_lex_docs = Path(lex_docs["output"]).resolve()

            if actual_lex_docs is None:
                staged_swift = temp_root / "swift-out"
                staged_manifest["swift"]["output"] = str(staged_swift)
                targets.append(
                    ("Swift", "swift", actual_swift, staged_swift, ".swift", swift_header)
                )
                swift_format_dirs.append((staged_swift, actual_swift))
            elif actual_lex_docs.is_relative_to(actual_swift):
                staged_swift = temp_root / "swift-out"
                staged_lex_docs = staged_swift / actual_lex_docs.relative_to(actual_swift)
                staged_manifest["swift"]["output"] = str(staged_swift)
                staged_manifest["swift"]["lexicon_documents"]["output"] = str(staged_lex_docs)
                targets.append(
                    ("Swift", "swift", actual_swift, staged_swift, ".swift", swift_header)
                )
                swift_format_dirs.append((staged_swift, actual_swift))
                if actual_lex_docs != actual_swift:
                    swift_format_dirs.append((staged_lex_docs, actual_lex_docs))
            elif actual_swift.is_relative_to(actual_lex_docs):
                staged_lex_docs = temp_root / "swift-lexicon-documents-out"
                staged_swift = staged_lex_docs / actual_swift.relative_to(actual_lex_docs)
                staged_manifest["swift"]["output"] = str(staged_swift)
                staged_manifest["swift"]["lexicon_documents"]["output"] = str(staged_lex_docs)
                targets.append(
                    (
                        "Swift",
                        "swift",
                        actual_lex_docs,
                        staged_lex_docs,
                        ".swift",
                        GENERATED_SWIFT_HEADER,
                    )
                )
                swift_format_dirs.append((staged_swift, actual_swift))
                swift_format_dirs.append((staged_lex_docs, actual_lex_docs))
            else:
                staged_swift = temp_root / "swift-out"
                staged_lex_docs = temp_root / "swift-lexicon-documents-out"
                staged_manifest["swift"]["output"] = str(staged_swift)
                staged_manifest["swift"]["lexicon_documents"]["output"] = str(staged_lex_docs)
                targets.append(
                    ("Swift", "swift", actual_swift, staged_swift, ".swift", swift_header)
                )
                targets.append(
                    (
                        "Swift (lexicon_documents)",
                        "swift",
                        actual_lex_docs,
                        staged_lex_docs,
                        ".swift",
                        GENERATED_SWIFT_HEADER,
                    )
                )
                swift_format_dirs.append((staged_swift, actual_swift))
                swift_format_dirs.append((staged_lex_docs, actual_lex_docs))

        kotlin_cfg = staged_manifest.get("kotlin")
        if (
            kind != "app-intents"
            and isinstance(kotlin_cfg, dict)
            and isinstance(kotlin_cfg.get("output"), str)
            and kotlin_cfg["output"]
            and language in ("kotlin", "both")
        ):
            actual_kotlin = Path(kotlin_cfg["output"]).resolve()
            staged_kotlin = temp_root / "kotlin-out"
            staged_manifest["kotlin"]["output"] = str(staged_kotlin)
            targets.append(
                ("Kotlin", "kotlin", actual_kotlin, staged_kotlin, ".kt", GENERATED_KOTLIN_HEADER)
            )

        swiftformat_runner = (
            _find_pinned_swiftformat(require=require_swiftformat)
            if swift_format_dirs and kind != "app-intents" and not no_format
            else None
        )

        staged_manifest_file = temp_root / "staged-manifest.json"
        staged_manifest_file.write_text(json.dumps(staged_manifest), encoding="utf-8")

        asyncio.run(
            run_manifest(
                str(staged_manifest_file),
                language,
                graph_path=graph_path,
                default_core_namespace_roots=default_core_roots,
            )
        )

        if swiftformat_runner is not None:
            (temp_root / ".swiftformat").write_text("", encoding="utf-8")
            for staged_dir, actual_dir in swift_format_dirs:
                _format_swift_directory(staged_dir, actual_dir, manifest, swiftformat_runner)

        yield targets


def _run_stdout_mode(
    manifest_path: Path,
    manifest: dict[str, Any],
    language: str,
    graph_path: str | None,
    default_core_roots: Sequence[str],
    no_format: bool = False,
) -> int:
    files: list[tuple[str, str, str]] = []
    with contextlib.redirect_stdout(sys.stderr):
        with _staged_manifest_outputs(
            manifest_path,
            manifest,
            language,
            graph_path=graph_path,
            default_core_roots=default_core_roots,
            no_format=no_format,
            require_swiftformat=False,
        ) as targets:
            for _, lang_label, _, staged_dir, ext, header in targets:
                staged_files = _snapshot_owned_files(staged_dir, ext, header)
                for rel_path, payload in staged_files.items():
                    files.append((lang_label, rel_path, payload.decode("utf-8")))

    for idx, (lang_label, rel_path, content) in enumerate(files):
        if idx > 0:
            sys.stdout.write("\n")
        sys.stdout.write(f"// === [{lang_label}] {rel_path} ===\n")
        sys.stdout.write(content)
        if not content.endswith("\n"):
            sys.stdout.write("\n")
    return 0


def _run_check_mode(
    manifest_path: Path,
    manifest: dict[str, Any],
    language: str,
    graph_path: str | None,
    default_core_roots: Sequence[str],
    no_format: bool = False,
) -> int:
    with _staged_manifest_outputs(
        manifest_path,
        manifest,
        language,
        graph_path=graph_path,
        default_core_roots=default_core_roots,
        no_format=no_format,
        require_swiftformat=True,
    ) as targets:
        drift_messages: list[str] = []
        for label, _, actual_dir, staged_dir, ext, header in targets:
            actual_files = _snapshot_owned_files(actual_dir, ext, header)
            expected_files = _snapshot_owned_files(staged_dir, ext, header)
            missing = sorted(set(expected_files) - set(actual_files))
            stale = sorted(set(actual_files) - set(expected_files))
            modified = sorted(
                rel for rel in (set(expected_files) & set(actual_files))
                if expected_files[rel] != actual_files[rel]
            )
            for rel in missing:
                drift_messages.append(f"  [{label} missing]  {actual_dir / rel}")
            for rel in modified:
                drift_messages.append(f"  [{label} modified] {actual_dir / rel}")
            for rel in stale:
                drift_messages.append(f"  [{label} stale]    {actual_dir / rel}")

        if drift_messages:
            print(
                f"Generated outputs are out of date with {manifest_path}:",
                file=sys.stderr,
            )
            for msg in drift_messages:
                print(msg, file=sys.stderr)
            print(
                f"Run `petrel-gen generate --manifest {manifest_path}` to update.",
                file=sys.stderr,
            )
            return 1

    print("Generated outputs are up to date.")
    return 0


def cmd_generate(args: argparse.Namespace) -> int:
    manifest_arg = args.manifest or DEFAULT_MANIFEST_FILENAME
    manifest_path = Path(manifest_arg).resolve()
    if not manifest_path.is_file():
        print(
            f"error: manifest file not found: {manifest_arg}\n"
            "hint: run `petrel-gen init --namespace xyz.statusphere --name PetrelStatusphere` "
            "to scaffold a new overlay project, or pass `--manifest <path>`.",
            file=sys.stderr,
        )
        return 1

    try:
        manifest = _loads_json_bytes(manifest_path.read_bytes())
    except Exception as exc:
        print(f"error: failed to parse manifest {manifest_path}: {exc}", file=sys.stderr)
        return 1
    if not isinstance(manifest, dict):
        print(
            f"error: manifest {manifest_path} must be a JSON object (got {type(manifest).__name__})",
            file=sys.stderr,
        )
        return 1

    language = args.language or "both"
    no_format = bool(getattr(args, "no_format", False))
    default_core_roots = load_bundled_core_namespace_roots()
    work_dir = _choose_working_directory_for_manifest(manifest_path, manifest)

    previous_cwd = os.getcwd()
    os.chdir(work_dir)
    try:
        local_core_manifest = Path(work_dir) / "generator" / "manifests" / "petrel-core.json"
        default_graph = os.path.join(_GENERATOR_DIR, "package-graph.json")
        graph_path = (
            default_graph
            if local_core_manifest.is_file() and os.path.isfile(default_graph)
            else None
        )

        if args.stdout:
            return _run_stdout_mode(
                manifest_path,
                manifest,
                language,
                graph_path=graph_path,
                default_core_roots=default_core_roots,
                no_format=no_format,
            )

        if args.check:
            return _run_check_mode(
                manifest_path,
                manifest,
                language,
                graph_path=graph_path,
                default_core_roots=default_core_roots,
                no_format=no_format,
            )

        pkg_cfg = manifest.get("package")
        kind = pkg_cfg.get("kind", "core") if isinstance(pkg_cfg, dict) else "core"
        wants_swift_format = (
            not no_format
            and kind != "app-intents"
            and _resolve_manifest_swift_output(manifest_path, manifest) is not None
            and language in ("swift", "both")
        )
        swiftformat_runner = (
            _find_pinned_swiftformat(require=False) if wants_swift_format else None
        )

        asyncio.run(
            run_manifest(
                str(manifest_path),
                language,
                graph_path=graph_path,
                default_core_namespace_roots=default_core_roots,
            )
        )

        if swiftformat_runner is not None:
            actual_swift = _resolve_manifest_swift_output(manifest_path, manifest)
            if actual_swift is not None:
                _format_swift_directory(actual_swift, actual_swift, manifest, swiftformat_runner)
            if isinstance(manifest.get("swift"), dict):
                lex_docs = manifest["swift"].get("lexicon_documents")
                if (
                    isinstance(lex_docs, dict)
                    and isinstance(lex_docs.get("output"), str)
                    and lex_docs["output"]
                ):
                    actual_lex_docs = Path(lex_docs["output"]).resolve()
                    if actual_lex_docs != actual_swift:
                        _format_swift_directory(
                            actual_lex_docs,
                            actual_lex_docs,
                            manifest,
                            swiftformat_runner,
                        )
    except Exception as exc:
        print(f"error: generation failed: {exc}", file=sys.stderr)
        return 1
    finally:
        os.chdir(previous_cwd)

    return 0


def _describe_property_schema(prop_schema: dict[str, Any]) -> str:
    prop_type = prop_schema.get("type", "unknown")
    fmt = prop_schema.get("format")
    if prop_type == "string" and fmt:
        return f"string ({fmt})"
    if prop_type == "ref":
        return f"ref -> {prop_schema.get('ref', '?')}"
    if prop_type == "union":
        refs = ", ".join(prop_schema.get("refs", []))
        return f"union [{refs}]"
    if prop_type == "array":
        items = prop_schema.get("items", {})
        return f"array<{_describe_property_schema(items)}>"
    return str(prop_type)


async def _prepare_inspect_context(
    lexicon: dict[str, Any],
    include_core_refs: bool,
) -> CycleDetector:
    cycle_detector = CycleDetector()
    lexicon_id = lexicon["id"]

    for def_name, def_schema in lexicon.get("defs", {}).items():
        if isinstance(def_schema, dict):
            cycle_detector.add_type(lexicon_id, def_name, def_schema)

    main_def = lexicon.get("defs", {}).get("main", {})
    if isinstance(main_def, dict) and main_def.get("type") in ("query", "procedure"):
        output = main_def.get("output")
        output_schema = output.get("schema") if isinstance(output, dict) else None
        if isinstance(output_schema, dict) and output_schema.get("type") == "object":
            cycle_detector.add_output_type(lexicon_id, output_schema)

    if include_core_refs:
        bundled_dir = get_bundled_core_lexicons_dir()
        if os.path.isdir(bundled_dir):
            await load_lexicons(
                [bundled_dir],
                DEFAULT_EXCLUDED_NAMESPACES,
                cycle_detector,
                skip_ids={lexicon_id},
            )

    cycle_detector.detect_cycles()
    return cycle_detector


def _extract_inspection_metadata(lexicon: dict[str, Any]) -> dict[str, Any]:
    lexicon_id = lexicon["id"]
    defs = lexicon["defs"]
    main_def = defs.get("main", {})
    primary_type = main_def.get("type", "defs-only") if isinstance(main_def, dict) else "defs-only"

    swift_symbol = convert_to_camel_case(lexicon_id)
    kotlin_symbol = convert_to_pascal_case(lexicon_id)
    ns_dir = get_namespace_path(lexicon_id)
    swift_path = f"Lexicons/{ns_dir}/{swift_symbol}.swift"
    kotlin_path = f"lexicons/{ns_dir.lower()}/{kotlin_symbol}.kt"

    ns_parts = [lower_camel(part) for part in namespace_segments(lexicon_id)]
    leaf_segment = lexicon_id.rsplit(".", 1)[-1]
    if primary_type in ("query", "procedure", "subscription"):
        accessor_parts = [*ns_parts, lower_camel(leaf_segment)]
    else:
        accessor_parts = ns_parts or [lower_camel(leaf_segment)]
    client_accessor = ".".join(["client", *accessor_parts])

    fields: list[dict[str, Any]] = []
    obj_source: dict[str, Any] | None = None
    if primary_type == "record" and isinstance(main_def.get("record"), dict):
        obj_source = main_def["record"]
    elif primary_type == "object":
        obj_source = main_def
    elif primary_type in ("query", "procedure"):
        params = main_def.get("parameters")
        if isinstance(params, dict) and isinstance(params.get("properties"), dict):
            req = set(params.get("required", []))
            for name, schema in params["properties"].items():
                fields.append(
                    {
                        "section": "parameters",
                        "name": name,
                        "required": name in req,
                        "lexicon_type": _describe_property_schema(schema),
                    }
                )
        inp = main_def.get("input", {})
        if isinstance(inp, dict) and isinstance(inp.get("schema"), dict):
            inp_schema = inp["schema"]
            req = set(inp_schema.get("required", []))
            for name, schema in inp_schema.get("properties", {}).items():
                fields.append(
                    {
                        "section": "input",
                        "name": name,
                        "required": name in req,
                        "lexicon_type": _describe_property_schema(schema),
                    }
                )
        out = main_def.get("output", {})
        if isinstance(out, dict) and isinstance(out.get("schema"), dict):
            out_schema = out["schema"]
            req = set(out_schema.get("required", []))
            for name, schema in out_schema.get("properties", {}).items():
                fields.append(
                    {
                        "section": "output",
                        "name": name,
                        "required": name in req,
                        "lexicon_type": _describe_property_schema(schema),
                    }
                )

    if obj_source is not None and isinstance(obj_source.get("properties"), dict):
        req = set(obj_source.get("required", []))
        for name, schema in obj_source["properties"].items():
            fields.append(
                {
                    "section": primary_type,
                    "name": name,
                    "required": name in req,
                    "lexicon_type": _describe_property_schema(schema),
                }
            )

    errors = [
        err.get("name")
        for err in main_def.get("errors", [])
        if isinstance(err, dict) and err.get("name")
    ] if isinstance(main_def, dict) else []

    return {
        "id": lexicon_id,
        "primary_type": primary_type,
        "record_key": main_def.get("key") if primary_type == "record" else None,
        "swift_symbol": swift_symbol,
        "kotlin_symbol": kotlin_symbol,
        "swift_path": swift_path,
        "kotlin_path": kotlin_path,
        "client_accessor": client_accessor,
        "definitions": list(defs.keys()),
        "fields": fields,
        "errors": errors,
    }


def cmd_inspect(args: argparse.Namespace) -> int:
    source_label = "<stdin>" if args.lexicon == "-" else args.lexicon
    effective_mode = args.language
    if effective_mode is None:
        effective_mode = "both" if args.stdout else "summary"

    need_swift = args.json or effective_mode in ("summary", "swift", "both")
    need_kotlin = (not args.json) and effective_mode in ("kotlin", "both")
    swift_code = ""
    kotlin_code = ""

    try:
        if args.lexicon == "-":
            raw_bytes = sys.stdin.buffer.read()
        else:
            lex_path = Path(args.lexicon)
            if not lex_path.is_file():
                print(f"error: lexicon file not found: {args.lexicon}", file=sys.stderr)
                return 1
            raw_bytes = lex_path.read_bytes()

        raw_doc = _loads_json_bytes(raw_bytes)
        lexicon = validate_lexicon_document(raw_doc, source_label=source_label)
        with contextlib.redirect_stdout(sys.stderr):
            cycle_detector = asyncio.run(
                _prepare_inspect_context(lexicon, include_core_refs=not args.no_core_refs)
            )
            if need_swift:
                swift_code = SwiftCodeGenerator(lexicon, cycle_detector).convert()
                if args.overlay:
                    swift_code = swift_code.replace(
                        "import Foundation",
                        "import Foundation\nimport Petrel",
                        1,
                    )
            if need_kotlin:
                kotlin_code = KotlinCodeGenerator(
                    lexicon,
                    cycle_detector,
                    overlay=args.overlay,
                ).convert()
        metadata = _extract_inspection_metadata(lexicon)
    except Exception as exc:
        print(f"error: failed to inspect {source_label}: {exc}", file=sys.stderr)
        return 1

    if args.json:
        print(json.dumps(metadata, indent=2))
        return 0

    if effective_mode == "swift":
        sys.stdout.write(swift_code)
        if not swift_code.endswith("\n"):
            sys.stdout.write("\n")
        return 0

    if effective_mode == "kotlin":
        sys.stdout.write(kotlin_code)
        if not kotlin_code.endswith("\n"):
            sys.stdout.write("\n")
        return 0

    if effective_mode == "both":
        sys.stdout.write(f"// === [swift] {metadata['swift_path']} ===\n")
        sys.stdout.write(swift_code)
        if not swift_code.endswith("\n"):
            sys.stdout.write("\n")
        sys.stdout.write(f"\n// === [kotlin] {metadata['kotlin_path']} ===\n")
        sys.stdout.write(kotlin_code)
        if not kotlin_code.endswith("\n"):
            sys.stdout.write("\n")
        return 0

    print(f"Lexicon:         {metadata['id']}")
    kind_detail = metadata["primary_type"]
    if metadata["record_key"]:
        kind_detail += f" (key: {metadata['record_key']})"
    print(f"Primary Type:    {kind_detail}")
    print(f"Swift Symbol:    {metadata['swift_symbol']}  ->  {metadata['swift_path']}")
    print(f"Kotlin Symbol:   {metadata['kotlin_symbol']}  ->  {metadata['kotlin_path']}")
    print(f"Client Path:     {metadata['client_accessor']}")
    print(f"Definitions:     {', '.join(metadata['definitions'])}")
    if metadata["fields"]:
        print("Fields:")
        for field in metadata["fields"]:
            req_badge = "required" if field["required"] else "optional"
            print(
                f"  - [{field['section']}] {field['name']}: "
                f"{field['lexicon_type']} ({req_badge})"
            )
    if metadata["errors"]:
        print(f"Declared Errors: {', '.join(metadata['errors'])}")
    print(
        "\nTip: pass `--language swift`, `--language kotlin`, or `--stdout` "
        "to print full generated code."
    )
    return 0


def cmd_info(args: argparse.Namespace) -> int:
    bundled_dir = Path(get_bundled_core_lexicons_dir())
    lexicon_count = sum(1 for _ in bundled_dir.rglob("*.json")) if bundled_dir.is_dir() else 0
    core_roots = list(load_bundled_core_namespace_roots())
    payload = {
        "version": CLI_VERSION,
        "bundled_core_lexicons_token": BUNDLED_CORE_LEXICONS_TOKEN,
        "bundled_core_lexicons_dir": str(bundled_dir),
        "bundled_core_lexicon_count": lexicon_count,
        "core_namespace_roots": core_roots,
        "templates_dir": os.path.join(_GENERATOR_DIR, "templates"),
    }
    if args.json:
        print(json.dumps(payload, indent=2))
    else:
        print(f"petrel-gen {payload['version']}")
        print(f"Bundled core lexicons: {payload['bundled_core_lexicon_count']} schemas")
        print(f"Bundled lexicon token: {payload['bundled_core_lexicons_token']}")
        print(f"Bundled lexicon path:  {payload['bundled_core_lexicons_dir']}")
        print(f"Core namespace roots:  {', '.join(core_roots)}")
    return 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="petrel-gen",
        description="Schema-first AT Protocol Lexicon code generator for Swift 6 and Kotlin.",
    )
    parser.add_argument(
        "--version",
        action="version",
        version=f"petrel-gen {CLI_VERSION}",
    )

    subparsers = parser.add_subparsers(dest="command", metavar="<command>")

    # petrel-gen init
    init_parser = subparsers.add_parser(
        "init",
        help="Scaffold a standalone custom Lexicon overlay package (Swift 6 + Kotlin)",
    )
    init_parser.add_argument(
        "--namespace",
        required=True,
        help="Root NSID prefix for your custom lexicons (e.g. xyz.statusphere)",
    )
    init_parser.add_argument(
        "--name",
        default=None,
        help="Overlay package name (e.g. PetrelStatusphere; derived from --namespace if omitted)",
    )
    init_parser.add_argument(
        "--dir",
        default=".",
        help="Target directory to scaffold into (default: current directory)",
    )
    init_parser.add_argument(
        "--sample-record",
        default="status",
        help="Sample record lexicon leaf name under --namespace (default: status)",
    )
    init_parser.add_argument(
        "--no-sample",
        action="store_true",
        help="Create an empty lexicons/ directory without a starter schema",
    )
    init_parser.add_argument(
        "--petrel-version",
        default=DEFAULT_PETREL_VERSION,
        help=f"Petrel SemVer baseline for .upToNextMinor(from:) (default: {DEFAULT_PETREL_VERSION})",
    )
    init_parser.add_argument(
        "--petrel-path",
        default=None,
        help="Optional local filesystem path to Petrel for monorepo/local Package.swift dependencies",
    )
    init_parser.add_argument(
        "--force",
        action="store_true",
        help="Overwrite existing scaffold files if present",
    )
    init_parser.set_defaults(handler=cmd_init)

    # petrel-gen generate
    gen_parser = subparsers.add_parser(
        "generate",
        help="Compile Lexicon schemas from a petrel-manifest.json into Swift 6 and Kotlin",
    )
    gen_parser.add_argument(
        "--manifest",
        default=None,
        help=f"Path to generation manifest JSON (default: {DEFAULT_MANIFEST_FILENAME})",
    )
    gen_parser.add_argument(
        "--language",
        choices=["swift", "kotlin", "both"],
        default="both",
        help="Target language(s) to emit (default: both)",
    )
    gen_mode_group = gen_parser.add_mutually_exclusive_group()
    gen_mode_group.add_argument(
        "--stdout",
        action="store_true",
        help="Print generated Swift/Kotlin sources to stdout without writing to disk",
    )
    gen_mode_group.add_argument(
        "--check",
        action="store_true",
        help="Verify generated directories on disk match current schemas without modifying files",
    )
    gen_parser.add_argument(
        "--no-format",
        action="store_true",
        help=f"Skip formatting generated or staged Swift outputs with pinned SwiftFormat {PINNED_SWIFTFORMAT_VERSION}",
    )
    gen_parser.set_defaults(handler=cmd_generate)

    # petrel-gen inspect
    inspect_parser = subparsers.add_parser(
        "inspect",
        help="Validate a single Lexicon JSON file and preview its Swift 6 / Kotlin types",
    )
    inspect_parser.add_argument(
        "lexicon",
        help="Path to a Lexicon .json file (or '-' to read JSON from stdin)",
    )
    inspect_parser.add_argument(
        "--language",
        choices=["summary", "swift", "kotlin", "both"],
        default=None,
        help="Output mode: summary card, swift source, kotlin source, or both (default: summary)",
    )
    inspect_parser.add_argument(
        "--stdout",
        action="store_true",
        help="Emit generated code directly to stdout (defaults to Swift + Kotlin unless --language is set)",
    )
    inspect_parser.add_argument(
        "--overlay",
        action="store_true",
        help="Render code preview with overlay imports (`import Petrel` / overlay Kotlin mode)",
    )
    inspect_parser.add_argument(
        "--json",
        action="store_true",
        help="Emit structured JSON inspection metadata",
    )
    inspect_parser.add_argument(
        "--no-core-refs",
        action="store_true",
        help="Skip loading bundled core AT Protocol lexicons for cross-schema ref resolution",
    )
    inspect_parser.set_defaults(handler=cmd_inspect)

    # petrel-gen info
    info_parser = subparsers.add_parser(
        "info",
        help="Show bundled core lexicon count, paths, and version details",
    )
    info_parser.add_argument(
        "--json",
        action="store_true",
        help="Emit info as JSON",
    )
    info_parser.set_defaults(handler=cmd_info)

    return parser


def cli_main(argv: Sequence[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    handler = getattr(args, "handler", None)
    if handler is None:
        parser.print_help()
        return 0
    return int(handler(args))


if __name__ == "__main__":
    raise SystemExit(cli_main())
