def _build_package_swift(
    package_name: str,
    petrel_version: str,
    petrel_path: str | None = None,
) -> str:
    if petrel_path:
        resolved_path_obj = Path(petrel_path)
        resolved_petrel = resolved_path_obj.as_posix()
        dependency_lines = [
            f'        .package(path: "{resolved_petrel}"),'
        ]
        petrel_package_id = resolved_path_obj.resolve().name or "Petrel"
    else:
        dependency_lines = [
            "        .package(",
            f'            url: "{DEFAULT_PETREL_GIT_URL}",',
            f'            .upToNextMinor(from: "{petrel_version}")',
            "        ),",
        ]
        petrel_package_id = "Petrel"

    lines = [
        "// swift-tools-version: 6.0",
        "",
        "import PackageDescription",
        "",
        "let package = Package(",
        f'    name: "{package_name}",',
        "    platforms: [",
        "        .macOS(.v15),",
        "        .iOS(.v18),",
        "        .tvOS(.v18),",
        "    ],",
        "    products: [",
        "        .library(",
        f'            name: "{package_name}",',
        f'            targets: ["{package_name}"]',
        "        ),",
        "    ],",
        "    dependencies: [",
        *dependency_lines,
        "    ],",
        "    targets: [",
        "        .target(",
        f'            name: "{package_name}",',
        "            dependencies: [",
        f'                .product(name: "Petrel", package: "{petrel_package_id}"),',
        "            ],",
        f'            path: "Sources/{package_name}",',
        "            swiftSettings: [",
        "                .swiftLanguageMode(.v6),",
        "            ]",
        "        ),",
        "    ]",
        ")",
        "",
    ]
    return "\n".join(lines)


