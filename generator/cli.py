def _loads_json_bytes(payload: bytes) -> Any:
    if _orjson is not None:
        return _orjson.loads(payload)
    return json.loads(payload.decode("utf-8"))


def load_bundled_core_namespace_roots() -> tuple[str, ...]:
    """Read core-owned namespace roots (e.g. ``('blue',)``) from bundled core manifest."""
    core_manifest_path = os.path.join(_GENERATOR_DIR, "manifests", "petrel-core.json")
    if not os.path.isfile(core_manifest_path):
        return ("blue",)
    try:
        with open(core_manifest_path, "rb") as handle:
            manifest = _loads_json_bytes(handle.read())
        roots = manifest.get("package", {}).get("core_namespace_roots", ())
        return normalize_core_namespace_roots(roots, source="bundled:core_namespace_roots")
    except (OSError, ValueError, TypeError, AttributeError):
        return ("blue",)


def derive_default_package_name(namespace: str) -> str:
    """Derive a PascalCase overlay package name from an NSID prefix.

    Examples:
        ``xyz.statusphere`` -> ``PetrelStatusphere``
        ``blue.moji`` -> ``PetrelMoji``
        ``com.example.notes`` -> ``PetrelExampleNotes``
    """
    segments = [seg.replace("-", "_") for seg in namespace.split(".") if seg]
    tail = segments[1:] if len(segments) >= 2 else segments
    suffix = "".join(convert_to_pascal_case(seg) for seg in tail)
    return f"Petrel{suffix}"


def validate_lexicon_document(doc: Any, source_label: str = "<input>") -> dict[str, Any]:
    """Validate top-level AT Protocol Lexicon v1 structure."""
    if not isinstance(doc, dict):
        raise ValueError(f"{source_label}: Lexicon document must be a JSON object")
    if doc.get("lexicon") != 1:
        raise ValueError(
            f"{source_label}: Expected '\"lexicon\": 1', got {doc.get('lexicon')!r}"
        )
    lexicon_id = doc.get("id")
    if not isinstance(lexicon_id, str) or not _NAMESPACE_PATTERN.fullmatch(lexicon_id):
        raise ValueError(
            f"{source_label}: 'id' must be a valid dotted NSID (got {lexicon_id!r})"
        )
    defs = doc.get("defs")
    if not isinstance(defs, dict) or not defs:
        raise ValueError(
            f"{source_label}: 'defs' must be a non-empty JSON object of definitions"
        )
    return doc


