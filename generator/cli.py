def cmd_init(args: argparse.Namespace) -> int:
    namespace = args.namespace.strip()
    if not _NAMESPACE_PATTERN.fullmatch(namespace):
        print(
            f"error: --namespace must be at least two dot-separated NSID segments "
            f"(e.g. 'xyz.statusphere'), got {namespace!r}",
            file=sys.stderr,
        )
        return 2

    package_name = (args.name or derive_default_package_name(namespace)).strip()
    if not _PACKAGE_NAME_PATTERN.fullmatch(package_name):
        print(
            f"error: --name must be a valid UpperCamelCase package identifier "
            f"(e.g. 'PetrelStatusphere'), got {package_name!r}",
            file=sys.stderr,
        )
        return 2

    sample_record = None if args.no_sample else (args.sample_record or "status").strip()
    if sample_record is not None and not _RECORD_SEGMENT_PATTERN.fullmatch(sample_record):
        print(
            f"error: --sample-record must be a single valid NSID segment "
            f"(e.g. 'status'), got {sample_record!r}",
            file=sys.stderr,
        )
        return 2

    target_dir = Path(args.dir).resolve()
    manifest_path = target_dir / DEFAULT_MANIFEST_FILENAME
    package_swift_path = target_dir / "Package.swift"
    swift_anchor_path = target_dir / "Sources" / package_name / f"{package_name}Overlay.swift"
    kotlin_gradle_path = target_dir / "kotlin" / "build.gradle.kts"
    kotlin_settings_path = target_dir / "kotlin" / "settings.gradle.kts"
    kotlin_gen_dir = target_dir / "kotlin/src/main/kotlin/blue/catbird/petrel/generated"
    makefile_path = target_dir / "Makefile"
    gitignore_path = target_dir / ".gitignore"

    planned_files: list[tuple[Path, str]] = [
        (
            manifest_path,
            json.dumps(_build_overlay_manifest(package_name, namespace), indent=2) + "\n",
        ),
        (
            package_swift_path,
            _build_package_swift(package_name, args.petrel_version, args.petrel_path),
        ),
        (swift_anchor_path, _build_swift_overlay_anchor(package_name, namespace)),
        (kotlin_gradle_path, _build_kotlin_gradle_kts(package_name)),
        (kotlin_settings_path, _build_kotlin_settings_kts(package_name)),
        (makefile_path, _build_makefile(package_name)),
        (gitignore_path, _build_gitignore()),
    ]

    sample_lexicon_id: str | None = None
    if sample_record is not None:
        sample_lexicon_id = f"{namespace}.{sample_record}"
        ns_rel_dir = Path(*namespace.split("."))
        sample_path = target_dir / "lexicons" / ns_rel_dir / f"{sample_record}.json"
        planned_files.append(
            (
                sample_path,
                json.dumps(_build_sample_lexicon(sample_lexicon_id), indent=2) + "\n",
            )
        )

    if not args.force:
        conflicts = [path for path, _ in planned_files if path.exists()]
        if conflicts:
            rel_list = ", ".join(str(p.relative_to(target_dir)) for p in conflicts)
            print(
                f"error: refusing to overwrite existing files in {target_dir}: {rel_list} "
                "(pass --force to overwrite)",
                file=sys.stderr,
            )
            return 1

    target_dir.mkdir(parents=True, exist_ok=True)
    (target_dir / "lexicons").mkdir(parents=True, exist_ok=True)
    kotlin_gen_dir.mkdir(parents=True, exist_ok=True)

    for file_path, content in planned_files:
        file_path.parent.mkdir(parents=True, exist_ok=True)
        file_path.write_text(content, encoding="utf-8")

    print(f"Initialized Petrel overlay package '{package_name}' ({namespace}.*) in {target_dir}")
    for file_path, _ in planned_files:
        print(f"  created {file_path.relative_to(target_dir)}")
    print("\nNext steps:")
    if Path.cwd().resolve() != target_dir:
        print(f"  cd {target_dir}")
    print(f"  petrel-gen generate --manifest {DEFAULT_MANIFEST_FILENAME}")
    print("  swift build")
    return 0


def _choose_working_directory_for_manifest(manifest_path: Path, manifest: dict[str, Any]) -> Path:
    """Resolve whether manifest paths are anchored at the manifest's directory or a repository root.

    Standalone overlay packages place ``petrel-manifest.json`` at the package root with
    paths (such as ``lexicons``) relative to ``manifest_path.parent``; prefer that directory
    first even when the caller invokes ``petrel-gen`` from another overlay checkout that also
    contains ``lexicons/``. Fall back to the Petrel repository root or CWD only when the
    manifest's ``emit`` directories do not exist relative to ``manifest_path.parent``.
    """
    cwd = Path.cwd()
    manifest_dir = manifest_path.parent.resolve()
    if cwd.resolve() == manifest_dir:
        return cwd

    emit_entries = [
        entry
        for entry in manifest.get("lexicons", {}).get("emit", [])
        if isinstance(entry, str) and entry not in BUNDLED_LEXICONS_ALIASES
    ]
    if not emit_entries:
        return manifest_dir

    if all((manifest_dir / entry).exists() for entry in emit_entries):
        return manifest_dir

    if manifest_dir.name == "manifests" and (manifest_dir.parent / "main.py").is_file():
        repo_root = manifest_dir.parent.parent
        if all((repo_root / entry).exists() for entry in emit_entries):
            return repo_root

    if manifest_dir.is_relative_to(cwd.resolve()) and all(
        (cwd / entry).exists() for entry in emit_entries
    ):
        return cwd

    return manifest_dir


def _resolve_manifest_swift_output(manifest_path: Path, manifest: dict[str, Any]) -> Path | None:
    """Resolve ``swift.output`` according to the manifest's ``package.kind``.

    Core and overlay manifests resolve ``swift.output`` against the active working
    directory selected for the manifest, whereas ``app-intents`` manifests resolve
    ``swift.output`` relative to ``manifest_path.parent`` (matching
    ``AppIntentsGenerator.generate()``).
    """
    swift_cfg = manifest.get("swift")
    if not isinstance(swift_cfg, dict):
        return None
    raw_out = swift_cfg.get("output")
    if not isinstance(raw_out, str) or not raw_out:
        return None
    pkg_cfg = manifest.get("package")
    kind = pkg_cfg.get("kind", "core") if isinstance(pkg_cfg, dict) else "core"
    if kind == "app-intents":
        manifest_dir = manifest_path.parent.resolve()
        return (Path(raw_out) if os.path.isabs(raw_out) else (manifest_dir / raw_out)).resolve()
    return Path(raw_out).resolve()


def _snapshot_owned_files(root: Path, extension: str, header: str) -> dict[str, bytes]:
    if not root.is_dir():
        return {}
    header_bytes = header.encode("utf-8")
    result: dict[str, bytes] = {}
    for path in sorted(root.rglob(f"*{extension}")):
        if path.is_file():
            payload = path.read_bytes()
            if payload.startswith(header_bytes):
                result[path.relative_to(root).as_posix()] = payload
    return result


